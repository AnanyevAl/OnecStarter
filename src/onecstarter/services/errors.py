"""Общий корень исключений слоя services.

Слой отдаёт наружу одну иерархию: слою представления достаточно поймать
`ServicesError`, чтобы показать пользователю сообщение вместо трассировки,
и разобрать конкретный тип там, где реакция различается. Наружу слой
не выпускает голых `ValueError` и `KeyError` — по ним не отличить нашу
диагностику от случайной ошибки в чужом коде.

Речь именно о выходящих исключениях. Внутри `user_data.load_user_data`
`ValueError` остаётся средством управления потоком при разборе испорченного
JSON и наружу не выходит — его ловит тот же модуль.

Иерархия плоская: базовый класс и осмысленные потомки, без промежуточных
уровней «на будущее». Все сообщения безопасны для показа пользователю —
строка соединения в них не попадает (инвариант 5 CLAUDE.md), а суррогатный
ключ привязки несёт только хеш.
"""  # noqa: RUF002


class ServicesError(Exception):
    """Любая ошибка слоя services, о которой стоит сказать пользователю."""  # noqa: RUF002


class UnknownItemError(ServicesError):
    """Ключа нет в текущем списке записей."""


class InvalidRequestError(ServicesError):
    """Состав запроса не позволяет выполнить операцию.

    Часть случаев — нарушение контракта вызывающего (`UPDATE` без
    `target_key`, `ADD` без имени), часть — операция, применённая не к тому
    виду секции: правка или удаление записи базы, адресованные секции-группе.
    У групп своя операция — она переписывает `Folder` вложенных записей,
    а обычная правка оставила бы их сиротами.
    """  # noqa: RUF002


class ReadOnlySourceError(ServicesError):
    """Попытка записи в запись из общего списка.

    Общие списки — источник только для чтения (дизайн плана 3, §3 и §5).
    """


class TargetGoneError(ServicesError):
    """Секция, которую собирались править, исчезла из файла."""


class ConcurrentEditError(ServicesError):
    """Файл меняется извне быстрее, чем мы успеваем записать патч."""


class EncodingRejectedError(ServicesError):
    """Текст не кодируется в исходную кодировку файла."""


class UserDataUnavailableError(ServicesError):
    """Файл наших данных существует, но прочитать или убрать его не удалось."""  # noqa: RUF002


class UserDataWriteError(ServicesError):
    """Наши данные не удалось записать: избранное и история не сохранены.

    Симметрична `UserDataUnavailableError`, которая закрывает чтение.
    До финального ревью симметрии не было: `OSError` из `save_user_data`
    выходила из `Workspace` голой, мимо всех ловцов слоя представления
    (они ловят `ServicesError`), и `Ctrl+D` молча не ставил звёздочку,
    а запуск базы молча не обновлял «Последний запуск» — под `pythonw.exe`
    даже без трассировки. Причины житейские: отвалившийся роуминг-профиль,
    антивирус, держащий файл, полный диск.

    Состояние в памяти при отказе откатывается (`Workspace._store_user`),
    поэтому экран после `rebuild()` показывает то же, что лежит в файле,
    а не то, что мы хотели туда записать.
    """  # noqa: RUF002


class LaunchError(ServicesError):
    """Запуск невозможен; сообщение безопасно показывать пользователю."""


class ServerError(ServicesError):
    """Общий корень ошибок локальных серверов 1С."""  # noqa: RUF002


class ServersUnavailableError(ServerError):
    """Файл профилей серверов существует, но прочитать или убрать его не удалось."""  # noqa: RUF002


class ConsoleRegistrationError(ServerError):
    """Регистрация консоли администрирования серверов не удалась."""


class ConsoleRegistrationDeclinedError(ServerError):
    """Пользователь отклонил запрос прав администратора — штатный исход, не сбой."""
