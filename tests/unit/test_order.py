"""Табличные тесты арифметики OrderInList (задача 15, план 4b, §4).

Табличные строки для «равных соседей» отличаются от тех, что дал бриф задачи
(`task-15-brief.md`, Step 1): у брифа `reorder_values([-1.0, -1.0, -1.0], 2,
None)` ожидал `{0: 0.0, 1: 1.0, 2: 2.0}` — но `after=None` значит «поставить
в начало» (docstring `order.reorder_values`), а этот результат отдаёт
переставляемой записи (индекс 2) наибольшее значение — она оказалась бы
в **конце**, а не в начале. Это противоречит и собственной семантике функции,
и соседней строке таблицы (`[10.0, 20.0], 1, None, {1: 9.0}` — там `after=None`
корректно даёт двигаемой записи меньшее значение). Ожидание здесь исправлено
на `{0: 1.0, 1: 2.0, 2: 0.0}` — переставляемая запись получает наименьшее
значение (двигаемая запись — первая), а `0` и `1` сохраняют взаимный порядок.
`test_reorder_to_front_of_degenerate_group_actually_sorts_first` проверяет это
не только по значению словаря, но и применением результата: пересчитывает
итоговый порядок сортировкой и убеждается, что двигаемая запись действительно
встаёт первой.

Готовый код `reorder_values` из брифа для этой строки (и для той же формы
с двумя равными соседями, `test_renumbering_stays_inside_the_group`) на деле
менял только одно значение (например, `{2: -2.0}`) — ветка `_between` с одним
краевым соседом никогда не запускала пересчёт группы, даже когда старое
значение двигаемой записи совпадало с этим единственным соседом.

**Круг правок 1 (ревью на самой сильной модели):** первая версия правки
(`_edge_tie`) сравнивала старое значение двигаемой записи с одним соседом —
и пересчитывала лишнее: на настоящих данных заказчика
(`[-1, -1, 311296, 311552, 311808, 312064]`) переписывала все шесть записей
ради одной. Решение заказчика: пересчитывать только когда **все** значения
группы совпадают буквально — `test_reorder_counter_example_from_customer_
data_touches_one_value` проверяет это на реальных числах.

Второй дефект того же круга правок: `_between` проверял `previous < middle <
following` по сырому `float`, а пишет `format_order` (15 значащих цифр,
`%.15g`) — округление могло дать текст, совпадающий с соседом
(`test_reorder_values_avoids_a_written_collision_between_close_neighbors`,
числа из самого ревью: `60.6814814814813`/`60.6814814814814`).
"""  # noqa: RUF002

import pytest

from onecstarter.services.order import format_order, reorder_values, sort_key


@pytest.mark.parametrize(
    ("orders", "moved", "after", "expected"),
    [
        # Есть зазор — меняется одно значение.
        ([10.0, 20.0, 30.0], 2, 0, {2: 15.0}),
        ([10.0, 20.0, 30.0], 0, 1, {0: 25.0}),
        # В начало и в конец — за пределы крайних значений.  # noqa: RUF003
        ([10.0, 20.0], 1, None, {1: 9.0}),
        ([10.0, 20.0], 0, 1, {0: 21.0}),
        # Никуда не двинули.
        ([10.0, 20.0], 1, 0, {}),
        ([10.0, 20.0], 0, None, {}),
        ([10.0], 0, None, {}),
        # Один элемент, некуда переставлять относительно себя же: rest пуст,
        # target всегда совпадает с range(1) — no-op раньше любых веток ниже.  # noqa: RUF003
        ([42.0], 0, None, {}),
        # after равен moved: явный no-op раньше вычисления rest/target.
        ([1.0, 2.0, 3.0], 1, 1, {}),
        # Равные соседи: зазора нет. Так выглядит наш собственный список
        # сразу после добавления — каждой записи пишется OrderInList=-1.
        # Ожидание исправлено относительно брифа — см. docstring модуля.
        ([-1.0, -1.0, -1.0], 2, None, {0: 1.0, 1: 2.0, 2: 0.0}),
        # Тот же вырожденный случай, но старое значение двигаемой записи
        # совпадает с единственным соседом с ДРУГОЙ стороны (сосед — по  # noqa: RUF003
        # значению после переноса, «before», не «after»).
        ([-1.0, -1.0, -1.0], 1, 2, {0: 0.0, 1: 2.0, 2: 1.0}),
        # Нет ключа OrderInList хотя бы у одного — интерполировать не от чего.  # noqa: RUF003
        ([10.0, None, 30.0], 2, None, {0: 1.0, 1: 2.0, 2: 0.0}),
        # Круг правок 1: зазор ЕСТЬ (не все соседи равны), но средний float  # noqa: RUF003
        # округляется format_order до текста, совпадающего с соседом  # noqa: RUF003
        # (60.68148148148135 -> "60.6814814814813" == сосед). Раньше это
        # проходило raw-float проверку и создавало ничью в файле; теперь
        # запускает пересчёт этих трёх элементов.
        (
            [60.6814814814813, 60.6814814814814, 100.0],
            2,
            0,
            {0: 0.0, 1: 2.0, 2: 1.0},
        ),
        # Круг правок 1, край: сосед настолько велик, что +1.0/-1.0 не меняют  # noqa: RUF003
        # число даже как сырой float (1.7e308 + 1.0 == 1.7e308).
        ([3.0, 1.7e308], 0, 1, {0: 1.0, 1: 0.0}),
    ],
)
def test_reorder_values(
    orders: list[float | None], moved: int, after: int | None, expected: dict[int, float]
) -> None:
    assert reorder_values(orders, moved, after) == expected


def test_reorder_to_front_of_degenerate_group_actually_sorts_first() -> None:
    """Не только значения словаря — реальный порядок после применения.

    Тот самый урок задач 9/12/13/14: значение может быть посчитано, но не
    дойти до наблюдаемой точки. Здесь наблюдаемая точка — сортировка
    результата тем же ключом, что и экран (`sort_key`), а не сырой словарь.
    """  # noqa: RUF002
    orders: list[float | None] = [-1.0, -1.0, -1.0]
    result = reorder_values(orders, 2, None)
    updated = list(orders)
    for index, value in result.items():
        updated[index] = value
    order_of_indices = sorted(range(len(updated)), key=lambda i: sort_key(updated[i]))
    assert order_of_indices[0] == 2


def test_reorder_values_avoids_a_written_collision_between_close_neighbors() -> None:
    """Проверка идёт по тому, что реально попадёт в файл, а не по float.

    Найдено ревью (круг правок 1, задача 15): среднее двух соседей, различных
    как `float`, после округления `format_order` до 15 значащих цифр может
    дать текст, буквально совпадающий с одним из соседей. Раздельно от
    табличной строки — здесь явно показано, что коллизия обнаруживается
    именно через `float(format_order(...))`, а не через сырой `middle`.
    """  # noqa: RUF002
    previous, following = 60.6814814814813, 60.6814814814814
    middle = (previous + following) / 2
    # Сырой float честно лежит строго между соседями...
    assert previous < middle < following
    # ...но записанный текст совпадает с одним из них: зазора для записи нет.  # noqa: RUF003
    assert format_order(middle) == format_order(previous)

    result = reorder_values([previous, following, 100.0], 2, 0)
    # Коллизия обнаружена — вместо одного «ничейного» значения пересчитаны
    # все три элемента группы.
    assert set(result) == {0, 1, 2}


def test_reorder_counter_example_from_customer_data_touches_one_value() -> None:
    """Реальные значения заказчика: зазор есть почти везде, кроме двух `-1`.

    Круг правок 1: прежняя `_edge_tie` сравнивала старое значение двигаемой
    записи только с ОДНИМ соседом и на этом списке пересчитывала ВСЕ шесть
    значений — при том, что зазор относительно `311296` и далее никуда
    не делся. Решение заказчика (пересчёт только при полном вырождении
    группы) должно тронуть ровно одну запись.
    """  # noqa: RUF002
    orders: list[float | None] = [-1.0, -1.0, 311296.0, 311552.0, 311808.0, 312064.0]
    result = reorder_values(orders, 1, None)
    assert len(result) == 1
    assert result == {1: -2.0}


def test_reorder_renumbers_before_writing_scientific_notation() -> None:
    """Четырнадцать обычных перетаскиваний записи под первую в одной группе —

    не синтетика, рядовая работа (находка ревью, круг правок 2, задача 15).
    `orders` здесь — состояние ровно перед 14-й перестановкой (записи A, B,
    C и N0..N12, где N-записи — цепочка, каждая из которых легла между A
    и предыдущей: A=0, N12=2⁻¹³, …, N0=2⁻¹, B=1, C=2; воспроизведено
    прогоном последовательности с целым `reorder_values`, числа не подобраны
    руками). Без проверки научной нотации 14-я перестановка отдала бы
    `{0: 6.103515625e-05}` — единственное значение в форме, которую
    `format_order` печатает как `"6.103515625e-05"`. Вместо этого должен
    сработать пересчёт: несколько значений, ни одно не в научной нотации.
    """  # noqa: RUF002
    orders: list[float | None] = [
        -1.0,  # новая запись — 14-я в цепочке, будет переставлена
        0.0,  # A — самая первая запись группы
        0.0001220703125,  # N12
        0.000244140625,  # N11
        0.00048828125,  # N10
        0.0009765625,  # N9
        0.001953125,  # N8
        0.00390625,  # N7
        0.0078125,  # N6
        0.015625,  # N5
        0.03125,  # N4
        0.0625,  # N3
        0.125,  # N2
        0.25,  # N1
        0.5,  # N0
        1.0,  # B
        2.0,  # C
    ]
    result = reorder_values(orders, 0, 1)  # переставить новую запись «после A»
    assert len(result) == len(orders)  # пересчитана вся группа, не одна запись
    assert all("e" not in format_order(value) for value in result.values())


def test_renumbering_stays_inside_the_group() -> None:
    """Пересчитывается одна группа, а не весь файл.

    Скил v8i-format, факт 5: пересчёт всего файла в плотную нумерацию
    переписывает его целиком и ломает round-trip. Локальный пересчёт
    при исчерпании зазора — вынужденный и редкий ([Р] решение спеки 4b, §4).
    Здесь группа вырождена целиком (`[-1, -1]`), поэтому пересчёт правомерен
    даже по суженному условию (`_all_equal`) круга правок 1.
    """  # noqa: RUF002
    assert set(reorder_values([-1.0, -1.0], 1, None)) == {0, 1}


def test_reorder_values_does_not_crash_on_out_of_contract_input() -> None:
    """Устойчивость к невозможному на практике входу, а не гарантия результата.

    `orders` обязан приходить уже отсортированным по показу — так его
    собирает единственный настоящий вызывающий, `edit._apply_reorder`
    (siblings сортируются `sort_key` перед вызовом). Невозрастающий список
    нарушает это предположение и никогда не возникает на практике, но
    функция обязана не падать и на нём — защита от будущего вызывающего,
    который забудет отсортировать соседей.
    """  # noqa: RUF002
    result = reorder_values([30.0, 20.0, 10.0], 0, 2)
    assert isinstance(result, dict)


@pytest.mark.parametrize(
    ("value", "text"),
    [(0.0, "0"), (-1.0, "-1"), (15.0, "15"), (60.6814814814813, "60.6814814814813")],
)
def test_format_order(value: float, text: str) -> None:
    """Целое пишется целым — так его пишет платформа, и diff файла не шумит."""  # noqa: RUF002
    assert format_order(value) == text


def _platform_rewrite(text: str) -> str:
    """Модель перезаписи `OrderInList` платформой: усечение до 15 значащих цифр.

    Правило снято замером 09.08.2026 на рабочем списке (скил `v8i-format`,
    раздел 5): из 17 дробных значений платформа переписала ровно два, и оба
    имели 16 значащих цифр; все, укладывавшиеся в 15, уцелели побайтно.
    """  # noqa: RUF002
    return f"{float(text):.15g}"


def test_platform_rewrite_model_reproduces_the_measurement() -> None:
    """Сначала проверяем модель, потом ею меряем — как с формулой контраста.

    Обе пары взяты из замера: слева то, что стояло в файле до перезаписи
    платформой, справа — что она записала вместо него.
    """  # noqa: RUF002
    assert _platform_rewrite("0.7223985890652509") == "0.722398589065251"
    assert _platform_rewrite("5.056790123456771") == "5.05679012345677"
    # Значение в пределах 15 цифр платформа не тронула вовсе.
    assert _platform_rewrite("60.6814814814813") == "60.6814814814813"


@pytest.mark.parametrize(
    "values",
    [
        [10.0, 20.0, 30.0],
        [0.0, 1.0],
        [-1.0, 0.0, 1.0],
        [1.0, 1.0000000000001],
        [60.6814814814813, 20.2271604938271, 3276.8],
        [0.240799529688417, 0.481599059376834, 0.7223985890652509],
    ],
)
def test_what_we_write_survives_the_platform_rewrite(values: list[float]) -> None:
    """Наше значение — неподвижная точка перезаписи платформой.

    Это половина пункта контрольной точки smoke №2 «порядок переживает
    запуск базы из штатного стартера», которую **нельзя** проверить
    в песочнице: подмена `APPDATA` изолирует наше приложение, но не
    `1cestart.exe` — платформа переменную окружения игнорирует (замер
    09.08.2026, план 4b, раздел контрольной точки). Живой файл ради этого
    пункта больше не трогаем: правило перезаписи измерено, и здесь
    проверяется, что наша запись под него не попадает.

    `format_order` печатает `.15g` — ровно ту точность, до которой усекает
    платформа, поэтому усечение на наших значениях тождественно. Тест
    сторожит именно это: замена на `.16g` или `.17g` ради «большей точности»
    сделала бы записанное нами не равным прочитанному обратно.
    """
    for index in range(len(values)):
        for target in range(len(values)):
            for produced in reorder_values(list(values), index, target).values():
                written = format_order(produced)
                assert _platform_rewrite(written) == written, produced


@pytest.mark.parametrize(
    ("order", "expected"),
    [(10.0, (False, 10.0)), (None, (True, 0.0)), (0.0, (False, 0.0)), (-1.0, (False, -1.0))],
)
def test_sort_key_matches_catalog(order: float | None, expected: tuple[bool, float]) -> None:
    """Тот же ключ, что у catalog.items_from_document — иначе дерево и патч разъедутся."""  # noqa: RUF002
    assert sort_key(order) == expected
